export function instantiateTemplate(
  template: ExampleTemplate,
  userId: string,
  customName?: string
): CvDoc {
  const now = new Date().toISOString();
  return {
    id: newId("cv_"),
    userId,
    rev: 1,
    name: customName || `${template.title} (Example)`,
    kind: "base",
    level: template.level,
    region: template.region,
    contact: {
      fullName: "Alex Morgan",
      email: "alex.morgan@example.com",
      phone: "+44 7700 900123",
      location: "London, UK",
      links: ["linkedin.com/in/alexmorgan-example"],
    },
    sections: template.getSections(),
    accepted: [],
    requirements: [],
    changes: [],
    design: {
      template: template.level === "student" ? "graduate" : "standard",
      pageSize: template.region === "us" ? "letter" : "a4",
      density: "default",
      pageTarget: template.level === "student" || template.level === "early" ? 1 : 2,
    },
    createdAt: now,
    updatedAt: now,
  };
}
